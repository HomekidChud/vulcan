fn js_field(name: &str) -> String {
    if JS_RESERVED.contains(&name) { format!("{name}_") } else { name.to_string() }
}

pub struct JsGen {
    body: String,
    indent: usize,
    locals: Vec<HashMap<String, (Ty, String)>>,
    counter: usize,
    fns: HashMap<String, (Vec<Ty>, Ty)>,
    structs: HashMap<String, Vec<(String, Ty)>>,
    enums: HashMap<String, Vec<String>>,
    sema: crate::sema::Tables,
    consts: HashMap<String, Ty>,
    impls: HashMap<(String, String), FnDecl>,
    defers: Vec<Vec<Stmt>>,
    externs: Vec<String>, // extern fn names -> routed to the host __ffi table
    cur_ret: Ty,
    is_main: bool,
}

fn method_js_name(sname: &str, mname: &str) -> String {
    format!("vm_{}_{}", sname, mname)
}

impl JsGen {
    fn fresh(&mut self, name: &str) -> String {
        self.counter += 1;
        format!("v{}_{}", self.counter, name)
    }

    fn is_enum(&self, name: &str) -> bool { self.sema.is_enum(name) }

    fn norm(&self, t: &Ty) -> Ty { self.sema.norm(t) }

    fn lookup(&self, name: &str) -> Option<(Ty, String)> {
        for scope in self.locals.iter().rev() {
            if let Some(v) = scope.get(name) {
                return Some(v.clone());
            }
        }
        None
    }

    fn field_ty(&self, recv_ty: &Ty, fname: &str) -> Ty { self.sema.field_ty(recv_ty, fname) }

    fn check_assignable(&self, from: &Ty, to: &Ty, what: &str) {
        self.sema.check_assignable(from, to, what);
    }

    // C copies structs and arrays by value; JS shares references. To keep the
    // backends byte-identical, a struct/array value is deep-cloned every time
    // C would copy it: let/assign to a variable, call argument, return value,
    // array element store, struct field store, for-in element binding.
    // Fresh literals need no clone.
    fn needs_clone(&self, t: &Ty) -> bool {
        // Structs are copied (C struct assignment). Arrays are NOT: the C
        // backend copies the Vec header and SHARES the heap data, so array
        // assignment/argument-passing is reference-like on every backend.
        matches!(self.norm(t), Ty::Struct(_)) // enums norm to I64
    }
    fn fresh_expr(e: &Expr) -> bool {
        matches!(e, Expr::StructLit { .. } | Expr::ArrayLit(_))
    }
    fn val_sem(&self, c: &str, e: &Expr, t: &Ty) -> String {
        if self.needs_clone(t) && !Self::fresh_expr(e) { format!("__sclone({c})") } else { c.to_string() }
    }

    fn cast(&self, c: &str, from: &Ty, to: &Ty) -> String {
        let from = self.norm(from);
        let to = self.norm(to);
        if from == to { return c.to_string(); }
        if from == Ty::I64 && to == Ty::F64 { return c.to_string(); }
        if from == Ty::F64 && to == Ty::I64 { return format!("Math.trunc({c})"); }
        panic!("vulcan: invalid cast {from:?} -> {to:?}");
    }

    fn array_elem(&self, t: &Ty) -> Ty { self.sema.array_elem(t) }

    fn gen_fn(&mut self, f: &FnDecl) {
        self.cur_ret = f.ret.clone();
        self.counter = 0;
        self.is_main = f.name == "main";
        self.defers.clear();
        self.locals.push(HashMap::new());
        for (pname, pty) in &f.params {
            self.locals.last_mut().unwrap().insert(pname.clone(), (pty.clone(), pname.clone()));
        }
        let params = f.params.iter().map(|(n, _)| n.clone()).collect::<Vec<_>>().join(", ");
        let _ = writeln!(self.body, "\nasync function {}({}) {{", f.name, params);
        self.indent = 1;
        self.emit_stmts(&f.body);
        self.line("}");
        self.locals.pop();
    }

    fn gen_method(&mut self, sname: &str, m: &FnDecl) {
        self.cur_ret = m.ret.clone();
        self.counter = 0;
        self.is_main = false;
        self.defers.clear();
        self.locals.push(HashMap::new());
        let has_self = m.params.first().map_or(false, |(n, _)| n == "self");
        let mut params = Vec::new();
        if has_self {
            self.locals.last_mut().unwrap().insert("self".into(), (Ty::Struct(sname.to_string()), "self".into()));
            params.push("self".to_string());
        }
        for (pname, pty) in &m.params {
            if has_self && pname == "self" { continue; }
            self.locals.last_mut().unwrap().insert(pname.clone(), (pty.clone(), pname.clone()));
            params.push(pname.clone());
        }
        let _ = writeln!(self.body, "\nasync function {}({}) {{", method_js_name(sname, &m.name), params.join(", "));
        self.indent = 1;
        self.emit_stmts(&m.body);
        self.line("}");
        self.locals.pop();
    }

    fn emit_pending_defers(&mut self) {
        let frames: Vec<Vec<Stmt>> = self.defers.clone();
        for frame in frames.iter().rev() {
            for stmt in frame.iter().rev() {
                self.gen_stmt(stmt);
            }
        }
    }

    fn emit_stmts(&mut self, stmts: &[Stmt]) {
        self.locals.push(HashMap::new());
        self.defers.push(Vec::new());
        for s in stmts {
            self.gen_stmt(s);
        }
        let frame = self.defers.pop().unwrap_or_default();
        for stmt in frame.iter().rev() {
            self.gen_stmt(stmt);
        }
        self.locals.pop();
    }

    fn line(&mut self, s: &str) {
        for _ in 0..self.indent { let _ = write!(self.body, "    "); }
        let _ = writeln!(self.body, "{s}");
    }

    fn gen_stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Let { name, ty, init } => {
                let (init_c, init_ty) = if let (Some(Ty::Array(_)), Expr::ArrayLit(items)) = (&ty, &init) {
                    if items.is_empty() {
                        (format!("[]"), ty.clone().unwrap())
                    } else {
                        self.gen_expr(&init)
                    }
                } else {
                    self.gen_expr(&init)
                };
                let final_ty = ty.clone().unwrap_or_else(|| init_ty.clone());
                self.check_assignable(&init_ty, &final_ty, "let initializer");
                let cvar = self.fresh(name);
                let init_c = self.val_sem(&init_c, init, &final_ty);
                self.line(&format!("let {cvar} = {init_c};"));
                self.locals.last_mut().unwrap().insert(name.clone(), (final_ty, cvar));
            }
            Stmt::Assign { target, value } => {
                let (val_c, val_ty) = self.gen_expr(value);
                match target {
                    Expr::Ident(name) => {
                        let (var_ty, cvar) = self.lookup(name).unwrap_or_else(|| panic!("vulcan: assign to undeclared `{name}`"));
                        let cast = self.cast(&val_c, &val_ty, &var_ty);
                        let cast = self.val_sem(&cast, value, &var_ty);
                        self.line(&format!("{cvar} = {cast};"));
                    }
                    Expr::Index(recv, idx) => {
                        let (recv_c, recv_ty) = self.gen_expr(recv);
                        let (idx_c, idx_ty) = self.gen_expr(idx);
                        let elem = self.array_elem(&recv_ty);
                        let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                        let cast = self.cast(&val_c, &val_ty, &elem);
                        let cast = self.val_sem(&cast, value, &elem);
                        self.line(&format!("__set({recv_c}, {idx_c}, {cast});"));
                    }
                    Expr::Field(recv, fname) => {
                        // struct references mean no copy dance is needed, even through array elements
                        let (recv_c, recv_ty) = self.gen_expr(recv);
                        let fty = self.field_ty(&recv_ty, fname);
                        let val_c = self.val_sem(&val_c, value, &fty);
                        self.line(&format!("{recv_c}.{} = {val_c};", js_field(fname)));
                    }
                    _ => panic!("vulcan: invalid assignment target"),
                }
            }
            Stmt::CompoundAssign { target, op, value } => {
                let (val_c, val_ty) = self.gen_expr(value);
                let bare_op = op.trim_end_matches('=').to_string();
                match target {
                    Expr::Ident(name) => {
                        let (var_ty, cvar) = self.lookup(name).unwrap_or_else(|| panic!("vulcan: assign to undeclared `{name}`"));
                        self.emit_op_assign(&cvar, &bare_op, op, &val_c, &val_ty, &var_ty);
                    }
                    Expr::Field(recv, fname) => {
                        let (recv_c, recv_ty) = self.gen_expr(recv);
                        let fty = self.field_ty(&recv_ty, fname);
                        let lhs = format!("{recv_c}.{}", js_field(fname));
                        self.emit_op_assign(&lhs, &bare_op, op, &val_c, &val_ty, &fty);
                    }
                    Expr::Index(recv, idx) => {
                        let (recv_c, recv_ty) = self.gen_expr(recv);
                        let (idx_c, idx_ty) = self.gen_expr(idx);
                        let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                        let elem = self.array_elem(&recv_ty);
                        let lhs = format!("__get({recv_c}, {idx_c})");
                        let applied = self.apply_op(&lhs, &bare_op, &val_c, &val_ty, &elem);
                        self.line(&format!("__set({recv_c}, {idx_c}, {applied});"));
                    }
                    _ => panic!("vulcan: invalid compound-assignment target"),
                }
            }
            Stmt::IncDec { target, delta } => {
                let op = if *delta > 0 { "++" } else { "--" };
                match target {
                    Expr::Ident(name) => {
                        let (_, cvar) = self.lookup(name).unwrap_or_else(|| panic!("vulcan: use of undeclared `{name}`"));
                        self.line(&format!("{cvar}{op};"));
                    }
                    Expr::Field(recv, fname) => {
                        let (recv_c, _) = self.gen_expr(recv);
                        self.line(&format!("{recv_c}.{}{op};", js_field(fname)));
                    }
                    Expr::Index(recv, idx) => {
                        let (recv_c, recv_ty) = self.gen_expr(recv);
                        let (idx_c, idx_ty) = self.gen_expr(idx);
                        let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                        self.line(&format!("__set({recv_c}, {idx_c}, __get({recv_c}, {idx_c}) + {delta});"));
                    }
                    _ => panic!("vulcan: invalid ++/-- target"),
                }
            }
            Stmt::If { cond, then, els } => {
                let (cond_c, cond_ty) = self.gen_expr(cond);
                if cond_ty != Ty::Bool { panic!("vulcan: if condition must be bool"); }
                self.line(&format!("if ({cond_c}) {{"));
                self.indent += 1;
                self.emit_stmts(then);
                self.indent -= 1;
                if let Some(els) = els {
                    self.line("} else {");
                    self.indent += 1;
                    self.emit_stmts(els);
                    self.indent -= 1;
                }
                self.line("}");
            }
            Stmt::While { cond, body } => {
                let (cond_c, cond_ty) = self.gen_expr(cond);
                if cond_ty != Ty::Bool { panic!("vulcan: while condition must be bool"); }
                self.line(&format!("while ({cond_c}) {{"));
                self.indent += 1;
                self.emit_stmts(body);
                self.indent -= 1;
                self.line("}");
            }
            Stmt::Loop { body } => {
                self.line("for (;;) {");
                self.indent += 1;
                self.emit_stmts(body);
                self.indent -= 1;
                self.line("}");
            }
            Stmt::For { var, from, to, step, inclusive, body } => {
                let (from_c, from_ty) = self.gen_expr(from);
                let (to_c, to_ty) = self.gen_expr(to);
                if self.norm(&from_ty) != Ty::I64 || self.norm(&to_ty) != Ty::I64 {
                    panic!("vulcan: for range bounds must be i64");
                }
                let cvar = self.fresh(var);
                let cmp = match (inclusive, step.map(|s| s < 0)) {
                    (false, None) | (false, Some(false)) => format!("{cvar} < {to_c}"),
                    (true, None) | (true, Some(false)) => format!("{cvar} <= {to_c}"),
                    (false, Some(true)) => format!("{cvar} > {to_c}"),
                    (true, Some(true)) => format!("{cvar} >= {to_c}"),
                };
                let inc = match step {
                    None => format!("{cvar}++"),
                    Some(s) => format!("{cvar} += {s}"),
                };
                self.line(&format!("for (let {cvar} = {from_c}; {cmp}; {inc}) {{"));
                self.locals.push(HashMap::new());
                self.locals.last_mut().unwrap().insert(var.clone(), (Ty::I64, cvar));
                self.indent += 1;
                for s in body { self.gen_stmt(s); }
                self.indent -= 1;
                self.line("}");
                self.locals.pop();
            }
            Stmt::ForIn { var, arr, body } => {
                let (ac, at) = self.gen_expr(arr);
                let elem = self.array_elem(&at);
                let it = self.fresh("it");
                self.line(&format!("const {it} = Array.from({ac});"));
                let ivar = format!("i_{it}");
                self.line(&format!("for (let {ivar} = 0; {ivar} < {it}.length; {ivar}++) {{"));
                let cvar = self.fresh(var);
                self.indent += 1;
                let it_elem = self.val_sem(&format!("{it}[{ivar}]"), arr, &elem);
                self.line(&format!("let {cvar} = {it_elem};"));
                self.locals.push(HashMap::new());
                self.locals.last_mut().unwrap().insert(var.clone(), (elem, cvar));
                self.defers.push(Vec::new());
                for s in body { self.gen_stmt(s); }
                let frame = self.defers.pop().unwrap_or_default();
                for stmt in frame.iter().rev() { self.gen_stmt(stmt); }
                self.indent -= 1;
                self.line("}");
                self.locals.pop();
            }
            Stmt::Match { scrutinee, arms, default } => {
                let (sc, st) = self.gen_expr(scrutinee);
                let tmp = self.fresh("m");
                self.line(&format!("const {tmp} = {sc};"));
                for (i, arm) in arms.iter().enumerate() {
                    let mut conds = Vec::new();
                    for p in &arm.pats {
                        let (pc, pt) = self.gen_expr(p);
                        if st == Ty::Str {
                            if pt != Ty::Str { panic!("vulcan: match pattern must be a string"); }
                            conds.push(format!("({tmp} === {pc})"));
                        } else if self.norm(&st) == Ty::I64 && self.norm(&pt) == Ty::I64 {
                            conds.push(format!("({tmp} === {pc})"));
                        } else {
                            panic!("vulcan: match pattern type mismatch");
                        }
                    }
                    let mut cond = conds.join(" || ");
                    if let Some(g) = &arm.guard {
                        let (gc, gt) = self.gen_expr(g);
                        if gt != Ty::Bool { panic!("vulcan: match guard must be bool"); }
                        cond = format!("(({cond}) && {gc})");
                    }
                    if i == 0 {
                        self.line(&format!("if ({cond}) {{"));
                    } else {
                        self.line(&format!("}} else if ({cond}) {{"));
                    }
                    self.indent += 1;
                    self.emit_stmts(&arm.body);
                    self.indent -= 1;
                }
                if let Some(d) = default {
                    self.line("} else {");
                    self.indent += 1;
                    self.emit_stmts(d);
                    self.indent -= 1;
                }
                self.line("}");
            }
            Stmt::Defer(body) => {
                self.defers.last_mut().unwrap().extend(body.iter().cloned());
            }
            Stmt::Assert { cond, msg, line: ln } => {
                let (cc, ct) = self.gen_expr(cond);
                if ct != Ty::Bool { panic!("vulcan: assert condition must be bool (line {ln})"); }
                let arg = match msg {
                    Some(m) => {
                        let (mc, mt) = self.gen_expr(m);
                        if mt != Ty::Str { panic!("vulcan: assert message must be a string"); }
                        format!("\"vulcan: assertion failed at line {ln}: \" + {mc} + \"\\n\"")
                    }
                    None => format!("\"vulcan: assertion failed at line {ln}\\n\""),
                };
                self.line(&format!("if (!({cc})) {{ process.stderr.write({arg}); process.exit(1); }}"));
            }
            Stmt::Return(e) => {
                match e {
                    None => {
                        if self.cur_ret == Ty::Void {
                            self.emit_pending_defers();
                            self.line("return;");
                        } else {
                            panic!("vulcan: return needs a value in this function");
                        }
                    }
                    Some(e) => {
                        let (ec, et) = self.gen_expr(e);
                        if self.cur_ret == Ty::Void { panic!("vulcan: cannot return a value from a void function"); }
                        let cast = self.cast(&ec, &et, &self.cur_ret);
                        let cast = self.val_sem(&cast, e, &self.cur_ret);
                        self.emit_pending_defers();
                        self.line(&format!("return {cast};"));
                    }
                }
            }
            Stmt::Break => self.line("break;"),
            Stmt::Continue => self.line("continue;"),
            Stmt::Expr(e) => {
                let (ec, _) = self.gen_expr(e);
                if !ec.is_empty() {
                    self.line(&format!("{ec};"));
                }
            }
        }
    }

    fn apply_op(&self, lhs: &str, bare_op: &str, val_c: &str, val_ty: &Ty, target_ty: &Ty) -> String {
        if bare_op == "/" && self.norm(target_ty) == Ty::I64 {
            format!("__idiv({lhs}, {val_c})")
        } else if bare_op == "%" {
            format!("(({lhs}) % ({val_c}))")
        } else {
            format!("(({lhs}) {bare_op} ({val_c}))")
        }
    }

    fn emit_op_assign(&mut self, lhs: &str, bare_op: &str, _op: &str, val_c: &str, val_ty: &Ty, target_ty: &Ty) {
        let val = self.cast(val_c, val_ty, target_ty);
        let applied = self.apply_op(lhs, bare_op, &val, target_ty, target_ty);
        self.line(&format!("{lhs} = {applied};"));
    }

    fn fmt_val(&self, c: &str, t: &Ty) -> String {
        match self.norm(t) {
            Ty::I64 => format!("String({c})"),
            Ty::F64 => format!("__g6({c})"),
            Ty::Bool => format!("(({c}) ? \"true\" : \"false\")"),
            Ty::Str => c.to_string(),
            Ty::Array(_) => {
                let elem = self.array_elem(t);
                let mapper = match self.norm(&elem) {
                    Ty::I64 => "String",
                    Ty::F64 => "__g6",
                    Ty::Bool => "(__b) => __b ? \"true\" : \"false\"",
                    Ty::Str => "(x) => x",
                    _ => panic!("vulcan: cannot print {t:?}"),
                };
                format!("(\"[\" + {c}.map({mapper}).join(\", \") + \"]\")")
            }
            _ => panic!("vulcan: cannot print {t:?}"),
        }
    }

    fn gen_expr(&mut self, e: &Expr) -> (String, Ty) {
        match e {
            Expr::Int(v) => (v.to_string(), Ty::I64),
            Expr::Float(v) => (v.to_string(), Ty::F64),
            Expr::Str(s) => (format!("\"{}\"", escape_js(s)), Ty::Str),
            Expr::Bool(b) => (if *b { "true".into() } else { "false".into() }, Ty::Bool),
            Expr::Char(c) => (c.to_string(), Ty::I64),
            Expr::Ident(name) => {
                if let Some((t, cvar)) = self.lookup(name) {
                    return (cvar, t);
                }
                if self.consts.contains_key(name) {
                    return (name.clone(), self.consts[name].clone());
                }
                if let Some(variants) = self.enums.get(name) {
                    let _ = variants;
                    return (name.clone(), Ty::Struct(name.clone()));
                }
                panic!("vulcan: use of undeclared `{name}`");
            }
            Expr::BinOp(l, op, r) => {
                let (lc, lt) = self.gen_expr(l);
                let (rc, rt) = self.gen_expr(r);
                match op.as_str() {
                    "+" if lt == Ty::Str && rt == Ty::Str => (format!("({lc} + {rc})"), Ty::Str),
                    "+" | "-" | "*" => {
                        if lt == Ty::Str || rt == Ty::Str { panic!("vulcan: + on strings requires both strings"); }
                        if lt == Ty::F64 || rt == Ty::F64 {
                            (format!("({lc} {op} {rc})"), Ty::F64)
                        } else {
                            (format!("({lc} {op} {rc})"), Ty::I64)
                        }
                    }
                    "/" => {
                        if lt == Ty::F64 || rt == Ty::F64 {
                            (format!("({lc} / {rc})"), Ty::F64)
                        } else {
                            (format!("__idiv({lc}, {rc})"), Ty::I64)
                        }
                    }
                    "%" => (format!("(({lc}) % ({rc}))"), Ty::I64),
                    "==" | "!=" | "<" | "<=" | ">" | ">=" => (format!("({lc} {op} {rc})"), Ty::Bool),
                    "&&" | "||" => (format!("({lc} {op} {rc})"), Ty::Bool),
                    "!" => (format!("(!{rc})"), Ty::Bool),
                    "-u" => {
                        if rt == Ty::F64 || lt == Ty::F64 { (format!("(-{rc})"), Ty::F64) }
                        else { (format!("(-{rc})"), Ty::I64) }
                    }
                    "~" => {
                        if self.norm(&rt) != Ty::I64 { panic!("vulcan: ~ requires an i64 operand"); }
                        (format!("__bnot({rc})"), Ty::I64)
                    }
                    "&" => (format!("__band({lc}, {rc})"), Ty::I64),
                    "|" => (format!("__bor({lc}, {rc})"), Ty::I64),
                    "^" => (format!("__bxor({lc}, {rc})"), Ty::I64),
                    "<<" => (format!("__shl({lc}, {rc})"), Ty::I64),
                    ">>" => (format!("__shr({lc}, {rc})"), Ty::I64),
                    other => panic!("vulcan: unknown operator `{other}`"),
                }
            }
            Expr::Call { callee, args } => self.gen_call(callee, args),
            Expr::Method { recv, name, args } => {
                let (recv_c, recv_ty) = self.gen_expr(recv);
                // user-defined impl methods take priority over same-named builtins
                if let Ty::Struct(sname) = &recv_ty {
                    if !self.is_enum(sname) {
                        if let Some(m) = self.impls.get(&(sname.clone(), name.clone())).cloned() {
                            let has_self = m.params.first().map_or(false, |(n, _)| n == "self");
                            let expected = m.params.len() - if has_self { 1 } else { 0 };
                            if args.len() != expected {
                                panic!("vulcan: method {sname}.{} takes {expected} arg(s)", m.name);
                            }
                            let mut call_args: Vec<String> = Vec::new();
                            if has_self {
                                // C passes &variable for `self` (mutating methods stick),
                                // and materializes non-variable receivers into a temp
                                // copy first. Match that: variable -> as-is, temp -> clone.
                                if matches!(&**recv, Expr::Ident(_)) {
                                    call_args.push(recv_c.clone());
                                } else {
                                    call_args.push(format!("__sclone({recv_c})"));
                                }
                            }
                            for (i, (_, pty)) in m.params.iter().enumerate() {
                                if has_self && i == 0 { continue; }
                                let arg = &args[if has_self { i - 1 } else { i }];
                                let (ac, at) = self.gen_expr(arg);
                                let cast = self.cast(&ac, &at, pty);
                                call_args.push(self.val_sem(&cast, arg, pty));
                            }
                            return (format!("await {}({})", method_js_name(sname, name), call_args.join(", ")), m.ret.clone());
                        }
                    }
                }
                match name.as_str() {
                    "len" => match self.norm(&recv_ty) {
                        Ty::Array(_) => (format!("({recv_c}.length)"), Ty::I64),
                        Ty::Str => (format!("({recv_c}.length)"), Ty::I64),
                        other => panic!("vulcan: .len() on {other:?}"),
                    },
                    "push" => {
                        if args.len() != 1 { panic!("vulcan: push takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        let elem = self.array_elem(&recv_ty);
                        let ac = self.cast(&ac, &at, &elem);
                        (format!("{recv_c}.push({ac})"), Ty::Void)
                    }
                    "pop" => {
                        if !args.is_empty() { panic!("vulcan: pop takes 0 args"); }
                        let elem = self.array_elem(&recv_ty);
                        (format!("{recv_c}.pop()"), elem)
                    }
                    "shift" => {
                        if !args.is_empty() { panic!("vulcan: shift takes 0 args"); }
                        let elem = self.array_elem(&recv_ty);
                        (format!("{recv_c}.shift()"), elem)
                    }
                    "last" => {
                        if !args.is_empty() { panic!("vulcan: last takes 0 args"); }
                        let elem = self.array_elem(&recv_ty);
                        (format!("{recv_c}[{recv_c}.length - 1]"), elem)
                    }
                    "contains" => {
                        if args.len() != 1 { panic!("vulcan: contains takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        if recv_ty == Ty::Str {
                            if at != Ty::Str { panic!("vulcan: string contains needs a string arg"); }
                            (format!("__contains({recv_c}, {ac})"), Ty::Bool)
                        } else {
                            let elem = self.array_elem(&recv_ty);
                            let ac = self.cast(&ac, &at, &elem);
                            (format!("__contains({recv_c}, {ac})"), Ty::Bool)
                        }
                    }
                    "sqrt" | "floor" | "abs" | "ceil" | "sin" | "cos" => {
                        if !args.is_empty() { panic!("vulcan: {name} takes 0 args"); }
                        match name.as_str() {
                            "sqrt" => (format!("Math.sqrt({recv_c})"), Ty::F64),
                            "floor" => (format!("Math.floor({recv_c})"), Ty::F64),
                            "ceil" => (format!("Math.ceil({recv_c})"), Ty::F64),
                            "sin" => (format!("Math.sin({recv_c})"), Ty::F64),
                            "cos" => (format!("Math.cos({recv_c})"), Ty::F64),
                            _ => (format!("Math.abs({recv_c})"), Ty::F64),
                        }
                    }
                    "upper" => (format!("{recv_c}.toUpperCase()"), Ty::Str),
                    "lower" => (format!("{recv_c}.toLowerCase()"), Ty::Str),
                    "trim" => (format!("{recv_c}.trim()"), Ty::Str),
                    "repeat" => {
                        if args.len() != 1 { panic!("vulcan: repeat takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        if at != Ty::I64 { panic!("vulcan: repeat needs an i64 count"); }
                        (format!("__repeat({recv_c}, {ac})"), Ty::Str)
                    }
                    "split" => {
                        if recv_ty != Ty::Str { panic!("vulcan: split is a string method"); }
                        if args.len() != 1 { panic!("vulcan: split takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        if at != Ty::Str { panic!("vulcan: split needs a string separator"); }
                        (format!("{recv_c}.split({ac})"), Ty::Array(Box::new(Ty::Str)))
                    }
                    "starts_with" => {
                        if recv_ty != Ty::Str { panic!("vulcan: starts_with is a string method"); }
                        if args.len() != 1 { panic!("vulcan: starts_with takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        if at != Ty::Str { panic!("vulcan: starts_with needs a string arg"); }
                        (format!("{recv_c}.startsWith({ac})"), Ty::Bool)
                    }
                    "ends_with" => {
                        if recv_ty != Ty::Str { panic!("vulcan: ends_with is a string method"); }
                        if args.len() != 1 { panic!("vulcan: ends_with takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        if at != Ty::Str { panic!("vulcan: ends_with needs a string arg"); }
                        (format!("{recv_c}.endsWith({ac})"), Ty::Bool)
                    }
                    "substring" => {
                        if recv_ty != Ty::Str { panic!("vulcan: substring is a string method"); }
                        if args.len() != 2 { panic!("vulcan: substring(start, end) takes 2 args"); }
                        let (a, at) = self.gen_expr(&args[0]);
                        if at != Ty::I64 { panic!("vulcan: substring needs i64 indices"); }
                        let (b, bt) = self.gen_expr(&args[1]);
                        if bt != Ty::I64 { panic!("vulcan: substring needs i64 indices"); }
                        (format!("__substring({recv_c}, {a}, {b})"), Ty::Str)
                    }
                    "find" => {
                        if recv_ty != Ty::Str { panic!("vulcan: find is a string method"); }
                        if args.len() != 1 { panic!("vulcan: find takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        if at != Ty::Str { panic!("vulcan: find needs a string arg"); }
                        (format!("{recv_c}.indexOf({ac})"), Ty::I64)
                    }
                    "remove" => {
                        if !matches!(recv_ty, Ty::Array(_)) { panic!("vulcan: remove is an array method"); }
                        if args.len() != 1 { panic!("vulcan: remove takes 1 arg (index)"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        if at != Ty::I64 { panic!("vulcan: remove needs an i64 index"); }
                        (format!("{recv_c}.splice({ac}, 1)"), Ty::Void)
                    }
                    "insert" => {
                        if !matches!(recv_ty, Ty::Array(_)) { panic!("vulcan: insert is an array method"); }
                        if args.len() != 2 { panic!("vulcan: insert(index, item) takes 2 args"); }
                        let (ic, it) = self.gen_expr(&args[0]);
                        if it != Ty::I64 { panic!("vulcan: insert needs an i64 index"); }
                        let (vc, vt) = self.gen_expr(&args[1]);
                        let elem = self.array_elem(&recv_ty);
                        let vc = self.cast(&vc, &vt, &elem);
                        (format!("{recv_c}.splice({ic}, 0, {vc})"), Ty::Void)
                    }
                    _ => panic!("vulcan: unknown method `.{name}()`"),
                }
            }
            Expr::Field(recv, fname) => {
                // enum path: Color.Red
                if let Expr::Ident(base) = &**recv {
                    if self.lookup(base).is_none() && !self.consts.contains_key(base) {
                        if let Some(variants) = self.enums.get(base) {
                            if variants.contains(fname) {
                                return (format!("{base}.{fname}"), Ty::Struct(base.clone()));
                            }
                        }
                    }
                }
                let (recv_c, recv_ty) = self.gen_expr(recv);
                if let Ty::Struct(sname) = recv_ty {
                    if self.is_enum(&sname) {
                        return (format!("{recv_c}.{fname}"), Ty::Struct(sname));
                    }
                    let fields = self.structs.get(&sname).unwrap_or_else(|| panic!("vulcan: unknown struct {sname}")).clone();
                    let fty = fields.iter().find(|(n, _)| n == fname)
                        .unwrap_or_else(|| panic!("vulcan: struct {sname} has no field {fname}")).1.clone();
                    (format!("{recv_c}.{}", js_field(fname)), fty)
                } else {
                    panic!("vulcan: field access on non-struct");
                }
            }
            Expr::Index(recv, idx) => {
                let (recv_c, recv_ty) = self.gen_expr(recv);
                let (idx_c, idx_ty) = self.gen_expr(idx);
                let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                if recv_ty == Ty::Str {
                    (format!("__chat({recv_c}, {idx_c})"), Ty::I64)
                } else {
                    let elem = self.array_elem(&recv_ty);
                    (format!("__get({recv_c}, {idx_c})"), elem)
                }
            }
            Expr::ArrayLit(items) => {
                if items.is_empty() {
                    panic!("vulcan: cannot infer type of empty array literal");
                }
                let mut cs = Vec::new();
                let mut elem = None;
                for item in items {
                    let (c, t) = self.gen_expr(item);
                    if let Some(first) = &elem {
                        if &t != first { panic!("vulcan: mixed array literal types"); }
                    } else {
                        elem = Some(t.clone());
                    }
                    // C memcpy's each element into the Vec: struct elements are copies
                    let c = if self.needs_clone(&t) { format!("__sclone({c})") } else { c };
                    cs.push(c);
                }
                (format!("[{}]", cs.join(", ")), Ty::Array(Box::new(elem.unwrap())))
            }
            Expr::StructLit { name, fields } => {
                let sdef = self.structs.get(name).unwrap_or_else(|| panic!("vulcan: unknown struct {name}")).clone();
                let mut inits = vec!["null".to_string(); sdef.len()];
                for (fname, fexpr) in fields {
                    let (fc, ft) = self.gen_expr(fexpr);
                    let pos = sdef.iter().position(|(n, _)| n == fname)
                        .unwrap_or_else(|| panic!("vulcan: struct {name} has no field {fname}"));
                    let target_ty = &sdef[pos].1;
                    let fc = self.cast(&fc, &ft, target_ty);
                    // C copies the field value into the struct: clone struct fields
                    let fc = if self.needs_clone(target_ty) { format!("__sclone({fc})") } else { fc };
                    inits[pos] = fc;
                }
                for (i, v) in inits.iter_mut().enumerate() {
                    if *v == "null" {
                        *v = self.default_val(&sdef[i].1).to_string();
                    }
                }
                let pairs: Vec<String> = sdef.iter().zip(inits.iter())
                    .map(|((n, _), v)| format!("{}: {v}", js_field(n)))
                    .collect();
                (format!("({{{}}})", pairs.join(", ")), Ty::Struct(name.clone()))
            }
            Expr::Interp(parts) => {
                let mut acc = String::new();
                for p in parts {
                    match p {
                        IPart::Lit(s) => acc.push_str(&escape_tmpl(s)),
                        IPart::E(e) => {
                            let (c, t) = self.gen_expr(e);
                            match self.norm(&t) {
                                Ty::I64 | Ty::Str => acc.push_str(&format!("${{{c}}}")),
                                Ty::F64 => acc.push_str(&format!("${{__g6({c})}}")),
                                Ty::Bool => acc.push_str(&format!("${{({c}) ? \"true\" : \"false\"}}")),
                                other => panic!("vulcan: cannot interpolate {other:?} into an f-string"),
                            }
                        }
                    }
                }
                (format!("`{acc}`"), Ty::Str)
            }
            Expr::As(inner, ty) => {
                let (c, t) = self.gen_expr(inner);
                (self.cast(&c, &t, ty), ty.clone())
            }
        }
    }

    fn default_val(&self, t: &Ty) -> String {
        match t {
            Ty::I64 => "0".into(),
            Ty::F64 => "0.0".into(),
            Ty::Bool => "false".into(),
            Ty::Str => "\"\"".into(),
            Ty::Array(_) => "[]".into(),
            Ty::Struct(_) => "null".into(),
            Ty::Void => "null".into(),
        }
    }

    fn gen_call(&mut self, callee: &str, args: &[Expr]) -> (String, Ty) {
        match callee {
            "print" | "put" => {
                let mut parts = Vec::new();
                for (i, a) in args.iter().enumerate() {
                    let (c, t) = self.gen_expr(a);
                    if i > 0 { parts.push("\" \"".to_string()); }
                    parts.push(self.fmt_val(&c, &t));
                }
                self.line(&format!("__out({});", parts.join(" + ")));
                if callee == "print" {
                    self.line("__out(\"\\n\");");
                }
                ("undefined".into(), Ty::Void)
            }
            "clock" => ("__clock()".into(), Ty::F64),
            "rand" => ("__rand()".into(), Ty::I64),
            "input" => ("(await __input())".into(), Ty::Str),
            "to_int" => {
                if args.len() != 1 { panic!("vulcan: to_int(s) takes 1 arg"); }
                let (c, t) = self.gen_expr(&args[0]);
                if t != Ty::Str { panic!("vulcan: to_int needs a string"); }
                (format!("__to_int({c})"), Ty::I64)
            }
            "to_float" => {
                if args.len() != 1 { panic!("vulcan: to_float(s) takes 1 arg"); }
                let (c, t) = self.gen_expr(&args[0]);
                if t != Ty::Str { panic!("vulcan: to_float needs a string"); }
                (format!("__to_float({c})"), Ty::F64)
            }
            "to_string" => {
                if args.len() != 1 { panic!("vulcan: to_string(n) takes 1 arg"); }
                let (c, t) = self.gen_expr(&args[0]);
                if t != Ty::I64 && t != Ty::F64 { panic!("vulcan: to_string needs i64 or f64"); }
                (format!("String({c})"), Ty::Str)
            }
            "file_read" => {
                if args.len() != 1 { panic!("vulcan: file_read(path) takes 1 arg"); }
                let (c, t) = self.gen_expr(&args[0]);
                if t != Ty::Str { panic!("vulcan: file_read needs a string path"); }
                (format!("__fs.readFileSync({c}, \"utf8\")"), Ty::Str)
            }
            "file_write" => {
                if args.len() != 2 { panic!("vulcan: file_write(path, contents) takes 2 args"); }
                let (p, pt) = self.gen_expr(&args[0]);
                if pt != Ty::Str { panic!("vulcan: file_write needs a string path"); }
                let (c, ct) = self.gen_expr(&args[1]);
                if ct != Ty::Str { panic!("vulcan: file_write needs string contents"); }
                (format!("(__fs.writeFileSync({p}, {c}), undefined)"), Ty::Void)
            }
            "file_exists" => {
                if args.len() != 1 { panic!("vulcan: file_exists(path) takes 1 arg"); }
                let (c, t) = self.gen_expr(&args[0]);
                if t != Ty::Str { panic!("vulcan: file_exists needs a string path"); }
                (format!("__fs.existsSync({c})"), Ty::Bool)
            }
            "arg_count" => (format!("(process.argv.length - 2)"), Ty::I64),
            "arg" => {
                if args.len() != 1 { panic!("vulcan: arg(i) takes 1 arg"); }
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::I64);
                (format!("(process.argv[{c} + 2] || \"\")"), Ty::Str)
            }
            "sleep_ms" => {
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::I64);
                (format!("(await __sleep({c}), undefined)"), Ty::Void)
            }
            "exit" => {
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::I64);
                (format!("(__exit({c}), undefined)"), Ty::Void)
            }
            "key_ready" => ("__key_ready()".into(), Ty::I64),
            "read_key" => ("__read_key()".into(), Ty::I64),
            "clear_screen" => ("(__clear_screen(), undefined)".into(), Ty::Void),
            "term_raw" | "term_normal" => ("undefined".into(), Ty::Void),
            "ms_now" => ("__ms_now()".into(), Ty::I64),
            "rand_int" => {
                if args.len() != 2 { panic!("vulcan: rand_int(lo, hi) takes 2 args"); }
                let (lo, lt) = self.gen_expr(&args[0]); let lo = self.cast(&lo, &lt, &Ty::I64);
                let (hi, ht) = self.gen_expr(&args[1]); let hi = self.cast(&hi, &ht, &Ty::I64);
                (format!("__rand_int({lo}, {hi})"), Ty::I64)
            }
            "print_at" => {
                if args.len() != 3 { panic!("vulcan: print_at(x, y, s) takes 3 args"); }
                let (x, xt) = self.gen_expr(&args[0]); let x = self.cast(&x, &xt, &Ty::I64);
                let (y, yt) = self.gen_expr(&args[1]); let y = self.cast(&y, &yt, &Ty::I64);
                let (s, st) = self.gen_expr(&args[2]);
                if st != Ty::Str { panic!("vulcan: print_at needs a string"); }
                (format!("(__print_at({x}, {y}, {s}), undefined)"), Ty::Void)
            }
            "set_color" => {
                if args.len() != 2 { panic!("vulcan: set_color(fg, bg) takes 2 args (use -1 to skip one)"); }
                let (fg, ft) = self.gen_expr(&args[0]); let fg = self.cast(&fg, &ft, &Ty::I64);
                let (bg, bt) = self.gen_expr(&args[1]); let bg = self.cast(&bg, &bt, &Ty::I64);
                (format!("(__set_color({fg}, {bg}), undefined)"), Ty::Void)
            }
            "screen_width" => ("__screen_w()".into(), Ty::I64),
            "screen_height" => ("__screen_h()".into(), Ty::I64),
            "canvas_width" => ("256".into(), Ty::I64),
            "canvas_height" => ("144".into(), Ty::I64),
            "clear" => {
                if args.len() != 1 { panic!("vulcan: clear(color) takes 1 arg"); }
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::I64);
                (format!("(__clear({c}), undefined)"), Ty::Void)
            }
            "draw_rect" => {
                if args.len() != 5 { panic!("vulcan: draw_rect(x, y, w, h, color) takes 5 args"); }
                let mut cs = Vec::new();
                for a in args.iter().take(4) {
                    let (c, t) = self.gen_expr(a);
                    cs.push(self.cast(&c, &t, &Ty::F64));
                }
                let (col, ct) = self.gen_expr(&args[4]);
                let col = self.cast(&col, &ct, &Ty::I64);
                (format!("(__draw_rect({}, {}, {}, {}, {col}), undefined)", cs[0], cs[1], cs[2], cs[3]), Ty::Void)
            }
            "draw_tri" => {
                if args.len() != 10 { panic!("vulcan: draw_tri(x0,y0,z0, x1,y1,z1, x2,y2,z2, color) takes 10 args"); }
                let mut cs = Vec::new();
                for a in args.iter().take(9) {
                    let (c, t) = self.gen_expr(a);
                    cs.push(self.cast(&c, &t, &Ty::F64));
                }
                let (col, ct) = self.gen_expr(&args[9]);
                let col = self.cast(&col, &ct, &Ty::I64);
                (format!("(__draw_tri({}, {}, {}, {}, {}, {}, {}, {}, {}, {col}), undefined)",
                    cs[0], cs[1], cs[2], cs[3], cs[4], cs[5], cs[6], cs[7], cs[8]), Ty::Void)
            }
            "draw_circle" => {
                if args.len() != 4 { panic!("vulcan: draw_circle(x, y, r, color) takes 4 args"); }
                let (x, xt) = self.gen_expr(&args[0]); let x = self.cast(&x, &xt, &Ty::F64);
                let (y, yt) = self.gen_expr(&args[1]); let y = self.cast(&y, &yt, &Ty::F64);
                let (r, rt) = self.gen_expr(&args[2]); let r = self.cast(&r, &rt, &Ty::F64);
                let (col, ct) = self.gen_expr(&args[3]); let col = self.cast(&col, &ct, &Ty::I64);
                (format!("(__draw_circle({x}, {y}, {r}, {col}), undefined)"), Ty::Void)
            }
            "draw_line" => {
                if args.len() != 5 { panic!("vulcan: draw_line(x1, y1, x2, y2, color) takes 5 args"); }
                let mut cs = Vec::new();
                for a in args.iter().take(4) {
                    let (c, t) = self.gen_expr(a);
                    cs.push(self.cast(&c, &t, &Ty::F64));
                }
                let (col, ct) = self.gen_expr(&args[4]);
                let col = self.cast(&col, &ct, &Ty::I64);
                (format!("(__draw_line({}, {}, {}, {}, {col}), undefined)", cs[0], cs[1], cs[2], cs[3]), Ty::Void)
            }
            "draw_text" => {
                if args.len() != 4 { panic!("vulcan: draw_text(x, y, text, color) takes 4 args"); }
                let (x, xt) = self.gen_expr(&args[0]); let x = self.cast(&x, &xt, &Ty::F64);
                let (y, yt) = self.gen_expr(&args[1]); let y = self.cast(&y, &yt, &Ty::F64);
                let (s, st) = self.gen_expr(&args[2]);
                let s = if st == Ty::Str { s } else { self.fmt_val(&s, &st) };
                let (col, ct) = self.gen_expr(&args[3]); let col = self.cast(&col, &ct, &Ty::I64);
                (format!("(__draw_text({x}, {y}, {s}, {col}), undefined)"), Ty::Void)
            }
            "present" => ("(__present(), undefined)".into(), Ty::Void),
            "mouse_x" => ("__mouse_x()".into(), Ty::F64),
            "mouse_dx" => ("__mouse_dx()".into(), Ty::F64),
            "mouse_dy" => ("__mouse_dy()".into(), Ty::F64),
            "mouse_y" => ("__mouse_y()".into(), Ty::F64),
            "mouse_down" => ("__mouse_down()".into(), Ty::Bool),
            "key_down" => {
                if args.len() != 1 { panic!("vulcan: key_down(code) takes 1 arg"); }
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::I64);
                (format!("__key_down({c})"), Ty::Bool)
            }
            "cursor_visible" => {
                let (c, t) = self.gen_expr(&args[0]); let c = self.cast(&c, &t, &Ty::I64);
                (format!("(__cursor_visible({c}), undefined)"), Ty::Void)
            }
            "sqrt" | "floor" | "ceil" | "sin" | "cos" | "tan" | "exp" | "log" | "pow" => {
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::F64);
                if callee == "pow" {
                    let (e, et) = self.gen_expr(&args[1]);
                    let e = self.cast(&e, &et, &Ty::F64);
                    (format!("Math.pow({c}, {e})"), Ty::F64)
                } else {
                    (format!("Math.{callee}({c})"), Ty::F64)
                }
            }
            "atan2" => {
                if args.len() != 2 { panic!("vulcan: atan2(y, x) takes 2 args"); }
                let (y, yt) = self.gen_expr(&args[0]);
                let y = self.cast(&y, &yt, &Ty::F64);
                let (x, xt) = self.gen_expr(&args[1]);
                let x = self.cast(&x, &xt, &Ty::F64);
                (format!("Math.atan2({y}, {x})"), Ty::F64)
            }
            "abs" => {
                let (c, t) = self.gen_expr(&args[0]);
                if t == Ty::I64 {
                    (format!("(({c}) < 0 ? -({c}) : ({c}))"), Ty::I64)
                } else if t == Ty::F64 {
                    (format!("Math.abs({c})"), Ty::F64)
                } else {
                    panic!("vulcan: abs needs an i64 or f64 argument");
                }
            }
            "min" | "max" => {
                if args.len() != 2 { panic!("vulcan: {callee} takes 2 args"); }
                let (a, at) = self.gen_expr(&args[0]);
                let (b, bt) = self.gen_expr(&args[1]);
                if at == Ty::F64 || bt == Ty::F64 {
                    let a = self.cast(&a, &at, &Ty::F64);
                    let b = self.cast(&b, &bt, &Ty::F64);
                    let f = if callee == "min" { "__min" } else { "__max" };
                    (format!("{f}({a}, {b})"), Ty::F64)
                } else if self.norm(&at) == Ty::I64 && self.norm(&bt) == Ty::I64 {
                    let f = if callee == "min" { "__min" } else { "__max" };
                    (format!("{f}({a}, {b})"), Ty::I64)
                } else {
                    panic!("vulcan: {callee} needs two numbers");
                }
            }
            "clamp" => {
                if args.len() != 3 { panic!("vulcan: clamp(x, lo, hi) takes 3 args"); }
                let (x, xt) = self.gen_expr(&args[0]);
                let (lo, lot) = self.gen_expr(&args[1]);
                let (hi, hit) = self.gen_expr(&args[2]);
                if xt == Ty::F64 || lot == Ty::F64 || hit == Ty::F64 {
                    let x = self.cast(&x, &xt, &Ty::F64);
                    let lo = self.cast(&lo, &lot, &Ty::F64);
                    let hi = self.cast(&hi, &hit, &Ty::F64);
                    (format!("(({x} < {lo}) ? {lo} : (({x} > {hi}) ? {hi} : {x}))"), Ty::F64)
                } else if self.norm(&xt) == Ty::I64 && self.norm(&lot) == Ty::I64 && self.norm(&hit) == Ty::I64 {
                    (format!("(({x} < {lo}) ? {lo} : (({x} > {hi}) ? {hi} : {x}))"), Ty::I64)
                } else {
                    panic!("vulcan: clamp needs three numbers");
                }
            }
            "lerp" => {
                if args.len() != 3 { panic!("vulcan: lerp(a, b, t) takes 3 args"); }
                let (a, at) = self.gen_expr(&args[0]);
                let (b, bt) = self.gen_expr(&args[1]);
                let (t, tt) = self.gen_expr(&args[2]);
                let a = self.cast(&a, &at, &Ty::F64);
                let b = self.cast(&b, &bt, &Ty::F64);
                let t = self.cast(&t, &tt, &Ty::F64);
                (format!("(({a}) + (({b}) - ({a})) * ({t}))"), Ty::F64)
            }
            "sign" => {
                if args.len() != 1 { panic!("vulcan: sign(x) takes 1 arg"); }
                let (x, xt) = self.gen_expr(&args[0]);
                if xt == Ty::F64 {
                    (format!("((({x}) > 0.0) ? 1.0 : ((({x}) < 0.0) ? -1.0 : 0.0))"), Ty::F64)
                } else if self.norm(&xt) == Ty::I64 {
                    (format!("((({x}) > 0) ? 1 : ((({x}) < 0) ? -1 : 0))"), Ty::I64)
                } else {
                    panic!("vulcan: sign needs a number");
                }
            }
            _ => {
                // user-defined function
                let (ptys, ret) = self.fns.get(callee).cloned()
                    .unwrap_or_else(|| panic!("vulcan: call to unknown function `{callee}`"));
                if ptys.len() != args.len() {
                    panic!("vulcan: `{callee}` takes {} arg(s), got {}", ptys.len(), args.len());
                }
                let mut call_args = Vec::new();
                for (a, pty) in args.iter().zip(ptys.iter()) {
                    let (ac, at) = self.gen_expr(a);
                    let cast = self.cast(&ac, &at, pty);
                    call_args.push(self.val_sem(&cast, a, pty));
                }
                if self.externs.iter().any(|n| n == callee) {
                    // FFI: the host provides this function via the __ffi table
                    (format!("__ffi.{callee}({})", call_args.join(", ")), ret)
                } else {
                    (format!("await {callee}({})", call_args.join(", ")), ret)
                }
            }
        }
    }
}

fn escape_tmpl(s: &str) -> String {
    // escape for a JS template literal
    let mut esc = String::new();
    for c in s.chars() {
        match c {
            '\\' => esc.push_str("\\\\"),
            '`' => esc.push_str("\\`"),
            '$' => esc.push_str("\\$"),
            '\n' => esc.push_str("\\n"),
            '\t' => esc.push_str("\\t"),
            '\r' => esc.push_str("\\r"),
            other => esc.push(other),
        }
    }
    esc
}
