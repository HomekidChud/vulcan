// Code generation + type checking for Vulcan. Emits C99, compiled with -O3.
use crate::parser::*;
use std::collections::HashMap;
use std::fmt::Write;

pub struct Codegen {
    out: String,
    body: String,
    struct_arrs: Vec<String>,
    indent: usize,
    locals: Vec<HashMap<String, (Ty, String)>>, // name -> (type, C name)
    counter: usize,
    fns: HashMap<String, (Vec<Ty>, Ty)>,
    structs: HashMap<String, Vec<(String, Ty)>>,
    enums: HashMap<String, Vec<String>>,
    consts: HashMap<String, (Ty, String)>, // name -> (type, C global name)
    defers: Vec<Vec<Stmt>>, // defer stack (LIFO at scope exit / return)
    impls: HashMap<(String, String), FnDecl>, // (struct, method) -> decl
    cur_ret: Ty,
    is_main: bool,
}

