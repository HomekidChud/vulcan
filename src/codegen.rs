pub fn generate(program: &[Item]) -> String {
    generate_inner(program, None)
}

// `tests`: when present, replaces `fn main` with a synthesized test runner.
pub fn generate_test(program: &[Item], tests: &[String]) -> String {
    generate_inner(program, Some(tests))
}

fn generate_inner(program: &[Item], tests: Option<&[String]>) -> String {
    let mut g = Codegen {
        out: String::new(),
        body: String::new(),
        struct_arrs: Vec::new(),
        indent: 1,
        locals: Vec::new(),
        counter: 0,
        fns: HashMap::new(),
        structs: HashMap::new(),
        enums: HashMap::new(),
        consts: HashMap::new(),
        defers: Vec::new(),
        impls: HashMap::new(),
        cur_ret: Ty::Void,
        is_main: false,
    };
    for item in program {
        match item {
            Item::Fn(f) => {
                g.fns.insert(f.name.clone(), (f.params.iter().map(|(_, t)| t.clone()).collect(), f.ret.clone()));
            }
            Item::Struct(s) => {
                g.structs.insert(s.name.clone(), s.fields.clone());
            }
            Item::Enum(e) => {
                g.enums.insert(e.name.clone(), e.variants.clone());
            }
            Item::Const(c) => {
                let cname = format!("vk_{}", c.name);
                g.consts.insert(c.name.clone(), (const_ty(c), cname));
            }
            Item::Impl(i) => {
                for m in &i.fns {
                    g.impls.insert((i.struct_name.clone(), m.name.clone()), m.clone());
                }
            }
            Item::Import(_) => {}
        }
    }
    let has_main = tests.is_some() || g.fns.contains_key("main");
    if !has_main {
        panic!("vulcan: program has no `fn main`");
    }
    if let Some(tests) = tests {
        if tests.is_empty() { panic!("vulcan: no `test_*` functions found"); }
    }
    let _ = write!(g.out, "\n// ---- constants ----\n");
    for item in program {
        if let Item::Const(c) = item {
            let (cval, _) = match (&c.value, &c.ty) {
                (ConstVal::Int(v), _) => (format!("INT64_C({v})"), ()),
                (ConstVal::Float(v), _) => (format!("{v}"), ()),
                (ConstVal::Str(s), _) => (format!("\"{}\"", escape_c(s)), ()),
                (ConstVal::Bool(b), _) => (format!("{}", if *b {1} else {0}), ()),
            };
            let _ = writeln!(g.out, "static const {} vk_{} = {};", g.ctype(&const_ty(c)), c.name, cval);
        }
    }
    let _ = write!(g.out, "\n// ---- enums ----\n");
    for item in program {
        if let Item::Enum(e) = item {
            for (i, v) in e.variants.iter().enumerate() {
                let _ = writeln!(g.out, "static const int64_t {}_{} = {};", e.name, v, i);
            }
        }
    }
    let _ = write!(g.out, "\n// ---- structs ----\n");
    for item in program {
        if let Item::Struct(s) = item {
            let _ = writeln!(g.out, "typedef struct {{");
            for (fname, fty) in &s.fields {
                let _ = writeln!(g.out, "    {} {};", g.ctype(fty), fname);
            }
            let _ = writeln!(g.out, "}} {};", s.name);
        }
    }
    let _ = write!(g.out, "\n// ---- functions ----\n");
    for item in program {
        if let Item::Fn(f) = item {
            if tests.is_some() && f.name == "main" { continue; }
            g.gen_fn(f);
        }
    }
    let _ = write!(g.out, "\n// ---- impl methods ----\n");
    // prototypes first so methods can call each other in any order
    for item in program {
        if let Item::Impl(i) = item {
            for m in &i.fns {
                let params = g.method_params_c(&i.struct_name, m);
                let _ = writeln!(g.out, "static {} {}({});", g.ctype(&m.ret), method_c_name(&i.struct_name, &m.name), params);
            }
        }
    }
    for item in program {
        if let Item::Impl(i) = item {
            for m in &i.fns {
                g.gen_method(&i.struct_name, m);
            }
        }
    }
    if let Some(tests) = tests {
        let mut body = vec![Stmt::Expr(Expr::Call {
            callee: "print".into(),
            args: vec![Expr::Str(format!("running {} test(s)", tests.len()))],
        })];
        for t in tests {
            body.push(Stmt::Expr(Expr::Call {
                callee: "print".into(),
                args: vec![Expr::Str(format!("  {t} ..."))],
            }));
            body.push(Stmt::Expr(Expr::Call { callee: t.clone(), args: vec![] }));
        }
        body.push(Stmt::Expr(Expr::Call {
            callee: "print".into(),
            args: vec![Expr::Str("all tests passed".into())],
        }));
        let main_decl = FnDecl {
            name: "main".into(),
            params: vec![],
            ret: Ty::Void,
            body,
        };
        g.gen_fn(&main_decl);
    }
    let mut out = PRELUDE.to_string();
    out.push_str(&g.out);
    for name in &g.struct_arrs {
        let _ = write!(out, "\ntypedef struct {{ {name}* data; int64_t len; int64_t cap; }} Vec_{name};\n");
        let _ = write!(out, "static Vec_{name} vs_{name}_new(int64_t n){{ Vec_{name} v; v.cap=(n>0?n:8); v.data=malloc(v.cap*sizeof({name})); v.len=0; return v; }}\n");
        let _ = write!(out, "static void vs_{name}_push(Vec_{name}* v, {name} x){{ if(v->len==v->cap){{ v->cap*=2; v->data=realloc(v->data,v->cap*sizeof({name})); }} v->data[v->len++]=x; }}\n");
        let _ = write!(out, "static {name} vs_{name}_get(Vec_{name}* v, int64_t i){{ if(i<0||i>=v->len){{ fprintf(stderr,\"vulcan: index out of bounds\\n\"); exit(1);}} return v->data[i]; }}\n");
        let _ = write!(out, "static void vs_{name}_set(Vec_{name}* v, int64_t i, {name} x){{ if(i<0||i>=v->len){{ fprintf(stderr,\"vulcan: index out of bounds\\n\"); exit(1);}} v->data[i]=x; }}\n");
        let _ = write!(out, "static {name} vs_{name}_pop(Vec_{name}* v){{ {name} z = {{0}}; return v->len>0 ? v->data[--v->len] : z; }}\n");
        let _ = write!(out, "static {name} vs_{name}_shift(Vec_{name}* v){{ {name} z = {{0}}; if(v->len==0) return z; {name} x=v->data[0]; memmove(v->data, v->data+1, (size_t)(v->len-1)*sizeof({name})); v->len--; return x; }}\n");
        let _ = write!(out, "static {name} vs_{name}_last(Vec_{name}* v){{ {name} z = {{0}}; return v->len>0 ? v->data[v->len-1] : z; }}\n");
    }
    out.push_str("\n// ---- program ----\n");
    out.push_str(&g.body);
    out.push('\n');
    out
}

fn const_ty(c: &ConstDecl) -> Ty {
    match &c.ty {
        Some(t) => t.clone(),
        None => match c.value {
            ConstVal::Int(_) => Ty::I64,
            ConstVal::Float(_) => Ty::F64,
            ConstVal::Str(_) => Ty::Str,
            ConstVal::Bool(_) => Ty::Bool,
        },
    }
}

fn escape_c(s: &str) -> String {
    let mut esc = String::new();
    for c in s.chars() {
        match c {
            '\n' => esc.push_str("\\n"),
            '\t' => esc.push_str("\\t"),
            '\r' => esc.push_str("\\r"),
            '"' => esc.push_str("\\\""),
            '\\' => esc.push_str("\\\\"),
            _ => esc.push(c),
        }
    }
    esc
}

// Names that would collide with C keywords or the compiler's prelude helpers.
const C_KEYWORDS: &[&str] = &[
    "auto", "break", "case", "char", "const", "continue", "default", "do", "double",
    "else", "enum", "extern", "float", "for", "goto", "if", "inline", "int", "long",
    "register", "restrict", "return", "short", "signed", "sizeof", "static", "struct",
    "switch", "typedef", "union", "unsigned", "void", "volatile", "while", "bool",
];
const PRELUDE_PREFIXES: &[&str] = &[
    "vi64_", "vf64_", "vbool_", "vstr_", "vs_", "vk_", "vto_", "vulcan_",
    "vmin_", "vmax_", "vclock", "vrand", "vsleep", "input_line", "term_raw",
    "term_normal", "key_ready", "read_key", "clear_screen",
    "vms_now", "vrand_int", "vprint_at", "vset_color", "vscreen_w", "vscreen_h", "vcursor_visible", "vchat",
];

fn method_c_name(sname: &str, mname: &str) -> String {
    format!("vm_{}_{}", sname, safe_c_name(mname))
}

fn safe_c_name(name: &str) -> String {
    if C_KEYWORDS.contains(&name) || PRELUDE_PREFIXES.iter().any(|p| name.starts_with(p)) {
        format!("vu_{name}")
    } else {
        name.to_string()
    }
}

impl Codegen {
    fn fresh(&mut self, name: &str) -> String {
        self.counter += 1;
        format!("v{}_{}", self.counter, name)
    }

    // enums are int64_t under the hood
    fn is_enum(&self, name: &str) -> bool { self.enums.contains_key(name) }

    fn ctype(&self, t: &Ty) -> String {
        match t {
            Ty::I64 => "int64_t".into(),
            Ty::F64 => "double".into(),
            Ty::Bool => "int8_t".into(),
            Ty::Str => "char*".into(),
            Ty::Void => "void".into(),
            Ty::Array(inner) => match &**inner {
                Ty::I64 => "VecI64".into(),
                Ty::F64 => "VecF64".into(),
                Ty::Bool => "VecBool".into(),
                Ty::Str => "VecStr".into(),
                Ty::Struct(name) if self.is_enum(name) => "VecI64".into(),
                Ty::Struct(name) => format!("Vec_{name}"),
                _ => panic!("vulcan: unsupported array element type"),
            },
            Ty::Struct(name) => {
                if self.is_enum(name) { "int64_t".into() } else { name.clone() }
            }
        }
    }

    // normalize enum types to I64 for assignability / casts
    fn norm(&self, t: &Ty) -> Ty {
        match t {
            Ty::Struct(n) if self.is_enum(n) => Ty::I64,
            Ty::Array(inner) => Ty::Array(Box::new(self.norm(inner))),
            other => other.clone(),
        }
    }

    fn lookup(&self, name: &str) -> Option<(Ty, String)> {
        for scope in self.locals.iter().rev() {
            if let Some(v) = scope.get(name) {
                return Some(v.clone());
            }
        }
        None
    }

    fn gen_fn(&mut self, f: &FnDecl) {
        self.cur_ret = f.ret.clone();
        self.counter = 0;
        self.is_main = f.name == "main";
        self.defers.clear();
        if self.is_main && !f.params.is_empty() {
            panic!("vulcan: main takes no parameters");
        }
        self.locals.push(HashMap::new());
        for (pname, pty) in &f.params {
            self.locals.last_mut().unwrap().insert(pname.clone(), (pty.clone(), pname.clone()));
        }
        self.indent = 1;
        let params = f.params.iter()
            .map(|(n, t)| format!("{} {}", self.ctype(t), n))
            .collect::<Vec<_>>()
            .join(", ");
        if self.is_main {
            let cast_ret = if f.ret == Ty::I64 { "int64_t r = vulcan_main(); return (int)r;" } else { "vulcan_main(); return 0;" };
            let _ = writeln!(self.body, "\nstatic {} vulcan_main(void) {{", self.ctype(&f.ret));
            self.emit_stmts(&f.body);
            if f.ret == Ty::Void {
                self.emit_pending_defers();
                self.line("return;");
            }
            self.line("}");
            let _ = writeln!(self.body, "\nint main(void) {{ {} }}", cast_ret);
        } else {
            let _ = writeln!(self.body, "\nstatic {} {}({}) {{", self.ctype(&f.ret), safe_c_name(&f.name), params);
            self.emit_stmts(&f.body);
            self.emit_pending_defers();
            self.line("}");
        }
        self.locals.pop();
    }

    fn gen_method(&mut self, sname: &str, m: &FnDecl) {
        self.cur_ret = m.ret.clone();
        self.counter = 0;
        self.is_main = false;
        self.defers.clear();
        self.locals.push(HashMap::new());
        let has_self = m.params.first().map_or(false, |(n, _)| n == "self");
        if has_self {
            // `self` dereferences the pointer parameter in every use site
            self.locals.last_mut().unwrap().insert("self".into(), (Ty::Struct(sname.to_string()), "(*__self)".into()));
        }
        for (pname, pty) in &m.params {
            if has_self && pname == "self" { continue; }
            self.locals.last_mut().unwrap().insert(pname.clone(), (pty.clone(), pname.clone()));
        }
        let params = self.method_params_c(sname, m);
        let _ = writeln!(self.body, "\nstatic {} {}({}) {{", self.ctype(&m.ret), method_c_name(sname, &m.name), params);
        self.indent = 1;
        self.emit_stmts(&m.body);
        self.emit_pending_defers();
        self.line("}");
        self.locals.pop();
    }

    fn method_params_c(&self, sname: &str, m: &FnDecl) -> String {
        let has_self = m.params.first().map_or(false, |(n, _)| n == "self");
        let mut params = Vec::new();
        if has_self {
            params.push(format!("{}* __self", sname));
        }
        for (n, t) in &m.params {
            if has_self && n == "self" { continue; }
            params.push(format!("{} {}", self.ctype(t), n));
        }
        if params.is_empty() { "void".into() } else { params.join(", ") }
    }

    fn emit_pending_defers(&mut self) {
        // LIFO: innermost scope first, last-registered first
        let frames: Vec<Vec<Stmt>> = self.defers.clone();
        for frame in frames.iter().rev() {
            for stmt in frame.iter().rev() {
                self.gen_stmt(stmt);
            }
        }
    }

    fn emit_stmts(&mut self, stmts: &[Stmt]) {
        self.locals.push(HashMap::new());
        self.defers.push(Vec::new());
        for s in stmts {
            self.gen_stmt(s);
        }
        // scope exit: run this block's defers
        let frame = self.defers.pop().unwrap_or_default();
        for stmt in frame.iter().rev() {
            self.gen_stmt(stmt);
        }
        self.locals.pop();
    }

    fn line(&mut self, s: &str) {
        for _ in 0..self.indent { let _ = write!(self.body, "    "); }
        let _ = writeln!(self.body, "{s}");
    }

    fn gen_stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Let { name, ty, init } => {
                let (init_c, init_ty) = if let (Some(Ty::Array(elem)), Expr::ArrayLit(items)) = (&ty, &init) {
                    if items.is_empty() {
                        // typed empty array: `let xs: [i64] = []`
                        let arr_ty = Ty::Array(elem.clone());
                        self.note_struct_array(elem);
                        let new = self.vec_helper(&arr_ty, "new");
                        (format!("{new}(0)"), arr_ty)
                    } else {
                        self.gen_expr(&init)
                    }
                } else {
                    self.gen_expr(&init)
                };
                let final_ty = ty.clone().unwrap_or_else(|| init_ty.clone());
                self.check_assignable(&init_ty, &final_ty, "let initializer");
                let cvar = self.fresh(name);
                self.line(&format!("{} {} = {};", self.ctype(&final_ty), cvar, init_c));
                self.locals.last_mut().unwrap().insert(name.clone(), (final_ty, cvar));
            }
            Stmt::Assign { target, value } => {
                let (val_c, val_ty) = self.gen_expr(value);
                match target {
                    Expr::Ident(name) => {
                        let (var_ty, cvar) = self.lookup(name).unwrap_or_else(|| panic!("vulcan: assign to undeclared `{name}`"));
                        let cast = self.cast(&val_c, &val_ty, &var_ty);
                        self.line(&format!("{cvar} = {cast};"));
                    }
                    Expr::Index(recv, idx) => {
                        let (recv_c, recv_ty) = self.gen_expr(recv);
                        let (idx_c, idx_ty) = self.gen_expr(idx);
                        let elem = self.array_elem(&recv_ty);
                        let set = self.vec_helper(&recv_ty, "set");
                        let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                        let cast = self.cast(&val_c, &val_ty, &elem);
                        self.line(&format!("{set}(&{recv_c}, {idx_c}, {cast});"));
                    }
                    Expr::Field(recv, fname) => {
                        if let Expr::Index(arr, idx) = &**recv {
                            let (arr_c, arr_ty) = self.gen_expr(arr);
                            let (idx_c, idx_ty) = self.gen_expr(idx);
                            let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                            let elem = self.array_elem(&arr_ty);
                            let get = self.vec_helper(&arr_ty, "get");
                            let set = self.vec_helper(&arr_ty, "set");
                            let fty = self.field_ty(&elem, fname);
                            let cast = self.cast(&val_c, &val_ty, &fty);
                            let tmp = self.fresh("tmp");
                            self.line(&format!("{{ {} {} = {}(&{}, {});", self.ctype(&elem), tmp, get, arr_c, idx_c));
                            self.line(&format!("    {tmp}.{fname} = {cast};"));
                            self.line(&format!("    {set}(&{arr_c}, {idx_c}, {tmp}); }}"));
                        } else {
                            let (recv_c, _) = self.gen_expr(recv);
                            self.line(&format!("{recv_c}.{fname} = {val_c};"));
                        }
                    }
                    _ => panic!("vulcan: invalid assignment target"),
                }
            }
            Stmt::CompoundAssign { target, op, value } => {
                let (val_c, val_ty) = self.gen_expr(value);
                let bare_op = op.trim_end_matches('=').to_string();
                match target {
                    Expr::Ident(name) => {
                        let (var_ty, cvar) = self.lookup(name).unwrap_or_else(|| panic!("vulcan: assign to undeclared `{name}`"));
                        let cast = self.cast(&val_c, &val_ty, &var_ty);
                        self.line(&format!("{cvar} {op} {cast};"));
                    }
                    Expr::Field(recv, fname) => {
                        if let Expr::Index(arr, idx) = &**recv {
                            let (arr_c, arr_ty) = self.gen_expr(arr);
                            let (idx_c, idx_ty) = self.gen_expr(idx);
                            let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                            let elem = self.array_elem(&arr_ty);
                            let get = self.vec_helper(&arr_ty, "get");
                            let set = self.vec_helper(&arr_ty, "set");
                            let fty = self.field_ty(&elem, fname);
                            let cast = self.cast(&val_c, &val_ty, &fty);
                            let tmp = self.fresh("tmp");
                            self.line(&format!("{{ {} {} = {}(&{}, {});", self.ctype(&elem), tmp, get, arr_c, idx_c));
                            self.line(&format!("    {tmp}.{fname} {op} {cast};"));
                            self.line(&format!("    {set}(&{arr_c}, {idx_c}, {tmp}); }}"));
                        } else {
                            let (recv_c, recv_ty) = self.gen_expr(recv);
                            let cast = self.cast(&val_c, &val_ty, &self.field_ty(&recv_ty, fname));
                            self.line(&format!("{recv_c}.{fname} {op} {cast};"));
                        }
                    }
                    Expr::Index(recv, idx) => {
                        let (recv_c, recv_ty) = self.gen_expr(recv);
                        let (idx_c, idx_ty) = self.gen_expr(idx);
                        let elem = self.array_elem(&recv_ty);
                        let set = self.vec_helper(&recv_ty, "set");
                        let get = self.vec_helper(&recv_ty, "get");
                        let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                        let cast = self.cast(&val_c, &val_ty, &elem);
                        self.line(&format!("{set}(&{recv_c}, {idx_c}, {get}(&{recv_c}, {idx_c}) {bare_op} {cast});"));
                    }
                    _ => panic!("vulcan: invalid compound-assignment target"),
                }
            }
            Stmt::IncDec { target, delta } => {
                let op = if *delta > 0 { "++" } else { "--" };
                match target {
                    Expr::Ident(name) => {
                        let (_, cvar) = self.lookup(name).unwrap_or_else(|| panic!("vulcan: use of undeclared `{name}`"));
                        self.line(&format!("{cvar}{op};"));
                    }
                    Expr::Field(recv, fname) => {
                        if let Expr::Index(arr, idx) = &**recv {
                            let (arr_c, arr_ty) = self.gen_expr(arr);
                            let (idx_c, idx_ty) = self.gen_expr(idx);
                            let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                            let elem = self.array_elem(&arr_ty);
                            let get = self.vec_helper(&arr_ty, "get");
                            let set = self.vec_helper(&arr_ty, "set");
                            let tmp = self.fresh("tmp");
                            self.line(&format!("{{ {} {} = {}(&{}, {});", self.ctype(&elem), tmp, get, arr_c, idx_c));
                            self.line(&format!("    {tmp}.{fname}{op};"));
                            self.line(&format!("    {set}(&{arr_c}, {idx_c}, {tmp}); }}"));
                        } else {
                            let (recv_c, _) = self.gen_expr(recv);
                            self.line(&format!("{recv_c}.{fname}{op};"));
                        }
                    }
                    Expr::Index(recv, idx) => {
                        let (recv_c, recv_ty) = self.gen_expr(recv);
                        let (idx_c, idx_ty) = self.gen_expr(idx);
                        let set = self.vec_helper(&recv_ty, "set");
                        let get = self.vec_helper(&recv_ty, "get");
                        let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                        self.line(&format!("{set}(&{recv_c}, {idx_c}, {get}(&{recv_c}, {idx_c}) + {delta});"));
                    }
                    _ => panic!("vulcan: invalid ++/-- target"),
                }
            }
            Stmt::If { cond, then, els } => {
                let (cond_c, cond_ty) = self.gen_expr(cond);
                if cond_ty != Ty::Bool { panic!("vulcan: if condition must be bool"); }
                self.line(&format!("if ({cond_c}) {{"));
                self.indent += 1;
                self.emit_stmts(then);
                self.indent -= 1;
                if let Some(els) = els {
                    self.line("} else {");
                    self.indent += 1;
                    self.emit_stmts(els);
                    self.indent -= 1;
                }
                self.line("}");
            }
            Stmt::While { cond, body } => {
                let (cond_c, cond_ty) = self.gen_expr(cond);
                if cond_ty != Ty::Bool { panic!("vulcan: while condition must be bool"); }
                self.line(&format!("while ({cond_c}) {{"));
                self.indent += 1;
                self.emit_stmts(body);
                self.indent -= 1;
                self.line("}");
            }
            Stmt::Loop { body } => {
                self.line("while (1) {");
                self.indent += 1;
                self.emit_stmts(body);
                self.indent -= 1;
                self.line("}");
            }
            Stmt::For { var, from, to, step, inclusive, body } => {
                let (from_c, from_ty) = self.gen_expr(from);
                let (to_c, to_ty) = self.gen_expr(to);
                if self.norm(&from_ty) != Ty::I64 || self.norm(&to_ty) != Ty::I64 {
                    panic!("vulcan: for range bounds must be i64");
                }
                let cvar = self.fresh(var);
                let cmp = match (inclusive, step.map(|s| s < 0)) {
                    (false, None) | (false, Some(false)) => format!("{cvar} < {to_c}"),
                    (true, None) | (true, Some(false)) => format!("{cvar} <= {to_c}"),
                    (false, Some(true)) => format!("{cvar} > {to_c}"),
                    (true, Some(true)) => format!("{cvar} >= {to_c}"),
                };
                let inc = match step {
                    None => format!("{cvar}++"),
                    Some(s) => format!("{cvar} += {s}"),
                };
                self.line(&format!("for (int64_t {cvar} = {from_c}; {cmp}; {inc}) {{"));
                self.locals.push(HashMap::new());
                self.locals.last_mut().unwrap().insert(var.clone(), (Ty::I64, cvar));
                self.indent += 1;
                for s in body { self.gen_stmt(s); }
                self.indent -= 1;
                self.line("}");
                self.locals.pop();
            }
            Stmt::ForIn { var, arr, body } => {
                let (ac, at) = self.gen_expr(arr);
                let elem = self.array_elem(&at);
                let it = self.fresh("it");
                let get = self.vec_helper(&at, "get");
                self.line(&format!("{} {} = {};", self.ctype(&at), it, ac));
                let ivar = format!("vi_{it}");
                self.line(&format!("for (int64_t {ivar} = 0; {ivar} < {it}.len; {ivar}++) {{"));
                let cvar = self.fresh(var);
                self.indent += 1;
                self.line(&format!("{} {} = {}(&{}, {});", self.ctype(&elem), cvar, get, it, ivar));
                self.locals.push(HashMap::new());
                self.locals.last_mut().unwrap().insert(var.clone(), (elem, cvar));
                self.defers.push(Vec::new());
                for s in body { self.gen_stmt(s); }
                let frame = self.defers.pop().unwrap_or_default();
                for stmt in frame.iter().rev() { self.gen_stmt(stmt); }
                self.indent -= 1;
                self.line("}");
                self.locals.pop();
            }
            Stmt::Match { scrutinee, arms, default } => {
                let (sc, st) = self.gen_expr(scrutinee);
                let tmp = self.fresh("m");
                self.line(&format!("{} {} = {};", self.ctype(&st), tmp, sc));
                for (i, arm) in arms.iter().enumerate() {
                    let mut conds = Vec::new();
                    for p in &arm.pats {
                        let (pc, pt) = self.gen_expr(p);
                        if st == Ty::Str {
                            if pt != Ty::Str { panic!("vulcan: match pattern must be a string"); }
                            conds.push(format!("(strcmp({tmp}, {pc})==0)"));
                        } else if self.norm(&st) == Ty::I64 && self.norm(&pt) == Ty::I64 {
                            conds.push(format!("({tmp} == {pc})"));
                        } else {
                            panic!("vulcan: match pattern type mismatch");
                        }
                    }
                    let cond = conds.join(" || ");
                    if i == 0 {
                        self.line(&format!("if ({cond}) {{"));
                    } else {
                        self.line(&format!("}} else if ({cond}) {{"));
                    }
                    self.indent += 1;
                    self.emit_stmts(&arm.body);
                    self.indent -= 1;
                }
                if let Some(d) = default {
                    self.line("} else {");
                    self.indent += 1;
                    self.emit_stmts(d);
                    self.indent -= 1;
                }
                self.line("}");
            }
            Stmt::Defer(body) => {
                self.defers.last_mut().unwrap().extend(body.iter().cloned());
            }
            Stmt::Assert { cond, msg, line: ln } => {
                let (cc, ct) = self.gen_expr(cond);
                if ct != Ty::Bool { panic!("vulcan: assert condition must be bool (line {ln})"); }
                let msgpart = match msg {
                    Some(m) => {
                        let (mc, mt) = self.gen_expr(m);
                        if mt != Ty::Str { panic!("vulcan: assert message must be a string"); }
                        format!(", {mc}")
                    }
                    None => String::new(),
                };
                let fmtstr = if msg.is_some() {
                    format!("vulcan: assertion failed at line {ln}: %s\\n")
                } else {
                    format!("vulcan: assertion failed at line {ln}\\n")
                };
                self.line(&format!(
                    "if (!({cc})) {{ fprintf(stderr, \"{fmtstr}\"{msgpart}); exit(1); }}"
                ));
            }
            Stmt::Return(e) => {
                match e {
                    None => {
                        if self.cur_ret == Ty::Void {
                            self.emit_pending_defers();
                            self.line("return;");
                        } else {
                            panic!("vulcan: return needs a value in this function");
                        }
                    }
                    Some(e) => {
                        let (ec, et) = self.gen_expr(e);
                        if self.cur_ret == Ty::Void { panic!("vulcan: cannot return a value from a void function"); }
                        let cast = self.cast(&ec, &et, &self.cur_ret);
                        self.emit_pending_defers();
                        self.line(&format!("return {cast};"));
                    }
                }
            }
            Stmt::Break => self.line("break;"),
            Stmt::Continue => self.line("continue;"),
            Stmt::Expr(e) => {
                let (ec, _) = self.gen_expr(e);
                if !ec.is_empty() && ec != "(void)0" {
                    self.line(&format!("{ec};"));
                }
            }
        }
    }

    fn field_ty(&self, recv_ty: &Ty, fname: &str) -> Ty {
        if let Ty::Struct(sname) = recv_ty {
            if let Some(fields) = self.structs.get(sname) {
                if let Some((_, t)) = fields.iter().find(|(n, _)| n == fname) {
                    return t.clone();
                }
            }
        }
        Ty::F64
    }

    fn check_assignable(&self, from: &Ty, to: &Ty, what: &str) {
        let from = self.norm(from);
        let to = self.norm(to);
        let ok = from == to || (from == Ty::I64 && to == Ty::F64);
        if !ok {
            panic!("vulcan: type mismatch in {what}: {from:?} vs {to:?}");
        }
    }

    fn cast(&self, c: &str, from: &Ty, to: &Ty) -> String {
        let from = self.norm(from);
        let to = self.norm(to);
        if from == to { return c.to_string(); }
        if from == Ty::I64 && to == Ty::F64 { return format!("(double)({c})"); }
        if from == Ty::F64 && to == Ty::I64 { return format!("(int64_t)({c})"); }
        panic!("vulcan: invalid cast {from:?} -> {to:?}");
    }

    fn array_elem(&self, t: &Ty) -> Ty {
        match t {
            Ty::Array(inner) => (**inner).clone(),
            _ => panic!("vulcan: indexing a non-array value ({t:?})"),
        }
    }

    fn vec_helper(&self, arr_ty: &Ty, kind: &str) -> String {
        let elem = self.array_elem(arr_ty);
        let prefix = if let Ty::Struct(name) = &elem {
            if self.is_enum(name) { "vi64".to_string() } else { format!("vs_{name}") }
        } else {
            match self.norm(&elem) {
                Ty::I64 => "vi64".to_string(),
                Ty::F64 => "vf64".to_string(),
                Ty::Bool => "vbool".to_string(),
                Ty::Str => "vstr".to_string(),
                _ => panic!("vulcan: unsupported array element type"),
            }
        };
        match kind {
            "new" => format!("{prefix}_new"),
            "push" => format!("{prefix}_push"),
            "get" => format!("{prefix}_get"),
            "set" => format!("{prefix}_set"),
            "pop" => format!("{prefix}_pop"),
            "shift" => format!("{prefix}_shift"),
            "last" => format!("{prefix}_last"),
            "contains" => {
                if let Ty::Struct(name) = &elem {
                    if self.is_enum(name) { return "vi64_contains".into(); }
                }
                match self.norm(&elem) {
                    Ty::I64 => "vi64_contains".into(),
                    Ty::F64 => "vf64_contains".into(),
                    Ty::Bool => "vbool_contains".into(),
                    Ty::Str => "vstr_contains_val".into(),
                    _ => panic!("vulcan: contains() not supported for this element type"),
                }
            }
            _ => panic!("unknown vec helper"),
        }
    }

    fn note_struct_array(&mut self, elem: &Ty) {
        if let Ty::Struct(name) = elem {
            if !self.is_enum(name) && !self.struct_arrs.contains(name) {
                self.struct_arrs.push(name.clone());
            }
        }
    }

    fn gen_expr(&mut self, e: &Expr) -> (String, Ty) {
        match e {
            Expr::Int(v) | Expr::Char(v) => (format!("INT64_C({v})"), Ty::I64),
            Expr::Float(v) => (format!("{v}"), Ty::F64),
            Expr::Str(s) => (format!("\"{}\"", escape_c(s)), Ty::Str),
            Expr::Bool(b) => (format!("{}", if *b {1} else {0}), Ty::Bool),
            Expr::Ident(name) => {
                if let Some((ty, cvar)) = self.lookup(name) {
                    (cvar, ty)
                } else if let Some((ty, cname)) = self.consts.get(name) {
                    (cname.clone(), ty.clone())
                } else {
                    panic!("vulcan: use of undeclared variable `{name}`");
                }
            }
            Expr::BinOp(l, op, r) => {
                let (lc, lt) = self.gen_expr(l);
                let (rc, rt) = self.gen_expr(r);
                match op.as_str() {
                    "+" if lt == Ty::Str && rt == Ty::Str => (format!("vstr_concat({lc}, {rc})"), Ty::Str),
                    "+" | "-" | "*" | "/" => {
                        if lt == Ty::Str || rt == Ty::Str { panic!("vulcan: + on strings requires both strings"); }
                        if lt == Ty::F64 || rt == Ty::F64 {
                            let lc = self.cast(&lc, &lt, &Ty::F64);
                            let rc = self.cast(&rc, &rt, &Ty::F64);
                            (format!("({lc} {op} {rc})"), Ty::F64)
                        } else {
                            (format!("({lc} {op} {rc})"), Ty::I64)
                        }
                    }
                    "%" => {
                        if lt != Ty::I64 || rt != Ty::I64 { panic!("vulcan: % is i64 only"); }
                        (format!("({lc} % {rc})"), Ty::I64)
                    }
                    "&" | "|" | "^" | "<<" | ">>" => {
                        if self.norm(&lt) != Ty::I64 || self.norm(&rt) != Ty::I64 {
                            panic!("vulcan: bitwise {op} requires i64 operands");
                        }
                        (format!("({lc} {op} {rc})"), Ty::I64)
                    }
                    "==" | "!=" | "<" | ">" | "<=" | ">=" => {
                        if lt == Ty::Str && rt == Ty::Str {
                            match op.as_str() {
                                "==" => (format!("(strcmp({lc},{rc})==0)"), Ty::Bool),
                                "!=" => (format!("(strcmp({lc},{rc})!=0)"), Ty::Bool),
                                _ => panic!("vulcan: strings support == and != only"),
                            }
                        } else {
                            let (lc, rc) = if lt == Ty::F64 || rt == Ty::F64 {
                                (self.cast(&lc, &lt, &Ty::F64), self.cast(&rc, &rt, &Ty::F64))
                            } else { (lc, rc) };
                            (format!("({lc} {op} {rc})"), Ty::Bool)
                        }
                    }
                    "&&" | "||" => (format!("({lc} {op} {rc})"), Ty::Bool),
                    "!" => (format!("(!{rc})"), Ty::Bool),
                    "-u" => {
                        if rt == Ty::F64 || lt == Ty::F64 { (format!("(-{rc})"), Ty::F64) }
                        else { (format!("(-{rc})"), Ty::I64) }
                    }
                    "~" => {
                        if self.norm(&rt) != Ty::I64 { panic!("vulcan: ~ requires an i64 operand"); }
                        (format!("(~{rc})"), Ty::I64)
                    }
                    _ => panic!("vulcan: bad operator {op}"),
                }
            }
            Expr::As(inner, ty) => {
                let (c, t) = self.gen_expr(inner);
                (self.cast(&c, &t, ty), ty.clone())
            }
            Expr::Interp(parts) => {
                let mut acc: Option<String> = None;
                for p in parts {
                    let piece = match p {
                        IPart::Lit(s) => format!("\"{}\"", escape_c(s)),
                        IPart::E(e) => {
                            let (c, t) = self.gen_expr(e);
                            match t {
                                Ty::I64 => format!("vto_str_i64({c})"),
                                Ty::F64 => format!("vto_str_f64({c})"),
                                Ty::Bool => format!("({c} ? \"true\" : \"false\")"),
                                Ty::Str => c,
                                _ => panic!("vulcan: cannot interpolate {t:?} into an f-string"),
                            }
                        }
                    };
                    acc = Some(match acc {
                        None => piece,
                        Some(a) => format!("vstr_concat({a}, {piece})"),
                    });
                }
                (acc.unwrap_or_else(|| "\"\"".into()), Ty::Str)
            }
            Expr::Call { callee, args } => self.gen_call(callee, args),
            Expr::Method { recv, name, args } => {
                let (recv_c, recv_ty) = self.gen_expr(recv);
                // user-defined impl methods take priority over same-named builtins
                if let Ty::Struct(sname) = &recv_ty {
                    if let Some(m) = self.impls.get(&(sname.clone(), name.clone())).cloned() {
                        if !matches!(&**recv, Expr::Ident(_)) {
                            panic!("vulcan: method calls need a simple variable receiver for now");
                        }
                        let has_self = m.params.first().map_or(false, |(n, _)| n == "self");
                        let expected = m.params.len() - if has_self { 1 } else { 0 };
                        if args.len() != expected {
                            panic!("vulcan: method {sname}.{} takes {expected} arg(s)", m.name);
                        }
                        let mut call_args: Vec<String> = Vec::new();
                        if has_self {
                            call_args.push(format!("&{recv_c}"));
                        }
                        for (i, (_, pty)) in m.params.iter().enumerate() {
                            if has_self && i == 0 { continue; }
                            let arg = &args[if has_self { i - 1 } else { i }];
                            let (ac, at) = self.gen_expr(arg);
                            let ac = self.cast(&ac, &at, pty);
                            call_args.push(ac);
                        }
                        return (format!("{}({})", method_c_name(sname, name), call_args.join(", ")), m.ret.clone());
                    }
                }
                match name.as_str() {
                    "len" => match recv_ty {
                        Ty::Array(_) => (format!("({recv_c}.len)"), Ty::I64),
                        Ty::Str => (format!("((int64_t)strlen({recv_c}))"), Ty::I64),
                        _ => panic!("vulcan: .len() on {recv_ty:?}"),
                    },
                    "push" => {
                        if args.len() != 1 { panic!("vulcan: push takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        let elem = self.array_elem(&recv_ty);
                        let ac = self.cast(&ac, &at, &elem);
                        let push = self.vec_helper(&recv_ty, "push");
                        (format!("{push}(&{recv_c}, {ac})"), Ty::Void)
                    }
                    "pop" => {
                        if !args.is_empty() { panic!("vulcan: pop takes 0 args"); }
                        let elem = self.array_elem(&recv_ty);
                        let pop = self.vec_helper(&recv_ty, "pop");
                        (format!("{pop}(&{recv_c})"), elem)
                    }
                    "shift" => {
                        if !args.is_empty() { panic!("vulcan: shift takes 0 args"); }
                        let elem = self.array_elem(&recv_ty);
                        let shift = self.vec_helper(&recv_ty, "shift");
                        (format!("{shift}(&{recv_c})"), elem)
                    }
                    "last" => {
                        if !args.is_empty() { panic!("vulcan: last takes 0 args"); }
                        let elem = self.array_elem(&recv_ty);
                        let last = self.vec_helper(&recv_ty, "last");
                        (format!("{last}(&{recv_c})"), elem)
                    }
                    "contains" => {
                        if recv_ty == Ty::Str {
                            if args.len() != 1 { panic!("vulcan: contains takes 1 arg"); }
                            let (ac, at) = self.gen_expr(&args[0]);
                            if at != Ty::Str { panic!("vulcan: string contains needs a string arg"); }
                            (format!("vstr_contains({recv_c}, {ac})"), Ty::Bool)
                        } else {
                            if args.len() != 1 { panic!("vulcan: contains takes 1 arg"); }
                            let (ac, at) = self.gen_expr(&args[0]);
                            let elem = self.array_elem(&recv_ty);
                            let ac = self.cast(&ac, &at, &elem);
                            let contains = self.vec_helper(&recv_ty, "contains");
                            (format!("{contains}(&{recv_c}, {ac})"), Ty::Bool)
                        }
                    }
                    "sqrt" | "floor" | "abs" | "ceil" | "sin" | "cos" => {
                        if !args.is_empty() { panic!("vulcan: {name} takes 0 args"); }
                        match name.as_str() {
                            "sqrt" => (format!("sqrt({recv_c})"), Ty::F64),
                            "floor" => (format!("floor({recv_c})"), Ty::F64),
                            "ceil" => (format!("ceil({recv_c})"), Ty::F64),
                            "sin" => (format!("sin({recv_c})"), Ty::F64),
                            "cos" => (format!("cos({recv_c})"), Ty::F64),
                            _ => (format!("fabs({recv_c})"), Ty::F64),
                        }
                    }
                    "upper" => (format!("vstr_upper({recv_c})"), Ty::Str),
                    "repeat" => {
                        if args.len() != 1 { panic!("vulcan: repeat takes 1 arg"); }
                        let (ac, at) = self.gen_expr(&args[0]);
                        if at != Ty::I64 { panic!("vulcan: repeat needs an i64 count"); }
                        (format!("vstr_repeat({recv_c}, {ac})"), Ty::Str)
                    }
                    "lower" => (format!("vstr_lower({recv_c})"), Ty::Str),
                    "trim" => (format!("vstr_trim({recv_c})"), Ty::Str),
                    _ => panic!("vulcan: unknown method `.{name}()`"),
                }
            }
            Expr::Field(recv, fname) => {
                // enum path: Color.Red / Color::Red
                if let Expr::Ident(base) = &**recv {
                    if self.lookup(base).is_none() {
                        if let Some(variants) = self.enums.get(base) {
                            if variants.contains(fname) {
                                return (format!("{base}_{fname}"), Ty::Struct(base.clone()));
                            }
                        }
                    }
                }
                let (recv_c, recv_ty) = self.gen_expr(recv);
                if let Ty::Struct(sname) = recv_ty {
                    let fields = self.structs.get(&sname).unwrap_or_else(|| panic!("vulcan: unknown struct {sname}")).clone();
                    let fty = fields.iter().find(|(n, _)| n == fname)
                        .unwrap_or_else(|| panic!("vulcan: struct {sname} has no field {fname}")).1.clone();
                    (format!("{recv_c}.{fname}"), fty)
                } else {
                    panic!("vulcan: field access on non-struct");
                }
            }
            Expr::Index(recv, idx) => {
                let (recv_c, recv_ty) = self.gen_expr(recv);
                let (idx_c, idx_ty) = self.gen_expr(idx);
                let idx_c = self.cast(&idx_c, &idx_ty, &Ty::I64);
                if recv_ty == Ty::Str {
                    // string indexing: s[i] yields the char code (bounds-checked, -1 when out of range)
                    (format!("vchat({recv_c}, {idx_c})"), Ty::I64)
                } else {
                    let elem = self.array_elem(&recv_ty);
                    let get = self.vec_helper(&recv_ty, "get");
                    (format!("{get}(&{recv_c}, {idx_c})"), elem)
                }
            }
            Expr::ArrayLit(items) => {
                if items.is_empty() {
                    panic!("vulcan: cannot infer type of empty array literal");
                }
                let mut tys = Vec::new();
                let mut cs = Vec::new();
                for item in items {
                    let (c, t) = self.gen_expr(item);
                    tys.push(t);
                    cs.push(c);
                }
                let elem = tys[0].clone();
                for t in &tys {
                    if t != &elem { panic!("vulcan: mixed array literal types"); }
                }
                let arr_ty = Ty::Array(Box::new(elem.clone()));
                self.note_struct_array(&elem);
                let new = self.vec_helper(&arr_ty, "new");
                let tmp = self.fresh("arr");
                self.line(&format!("{} {tmp} = {new}(0);", self.ctype(&arr_ty)));
                let push = self.vec_helper(&arr_ty, "push");
                for c in cs {
                    self.line(&format!("{push}(&{tmp}, {c});"));
                }
                (tmp, arr_ty)
            }
            Expr::StructLit { name, fields } => {
                let sdef = self.structs.get(name).unwrap_or_else(|| panic!("vulcan: unknown struct {name}")).clone();
                let mut inits = vec!["0".to_string(); sdef.len()];
                for (fname, fexpr) in fields {
                    let (fc, ft) = self.gen_expr(fexpr);
                    let pos = sdef.iter().position(|(n, _)| n == fname)
                        .unwrap_or_else(|| panic!("vulcan: struct {name} has no field {fname}"));
                    let target_ty = &sdef[pos].1;
                    let fc = self.cast(&fc, &ft, target_ty);
                    inits[pos] = fc;
                }
                (format!("({}){{{}}}", name, inits.join(", ")), Ty::Struct(name.clone()))
            }
        }
    }

    fn gen_call(&mut self, callee: &str, args: &[Expr]) -> (String, Ty) {
        match callee {
            "print" | "put" => {
                for (i, a) in args.iter().enumerate() {
                    if i > 0 { self.line("printf(\" \");"); }
                    let (c, t) = self.gen_expr(a);
                    match t {
                        Ty::I64 => self.line(&format!("printf(\"%lld\", (long long){c});")),
                        Ty::F64 => self.line(&format!("printf(\"%.6g\", {c});")),
                        Ty::Bool => self.line(&format!("printf(\"%s\", ({c} ? \"true\" : \"false\"));")),
                        Ty::Str => self.line(&format!("printf(\"%s\", {c});")),
                        Ty::Array(_) => {
                            let elem = self.array_elem(&t);
                            let is_enum_elem = matches!(&elem, Ty::Struct(n) if self.is_enum(n));
                            let (vec_ty, fmt_elem) = match self.norm(&elem) {
                                Ty::I64 => ("VecI64", "{v}.data[{i}]"),
                                Ty::F64 => ("VecF64", "{v}.data[{i}]"),
                                Ty::Bool => ("VecBool", "{v}.data[{i}] ? \"true\" : \"false\""),
                                Ty::Str => ("VecStr", "{v}.data[{i}]"),
                                _ if is_enum_elem => ("VecI64", "{v}.data[{i}]"),
                                _ => panic!("vulcan: cannot print {t:?}"),
                            };
                            let v = self.fresh("arr");
                            let i = self.fresh("i");
                            let fmt_elem = fmt_elem.replace("{v}", &v).replace("{i}", &i);
                            let fmt_elem = match self.norm(&elem) {
                                Ty::I64 => format!("(long long){fmt_elem}"),
                                _ if is_enum_elem => format!("(long long){fmt_elem}"),
                                _ => fmt_elem,
                            };
                            let fmt_str = match self.norm(&elem) {
                                Ty::I64 => "%lld",
                                Ty::F64 => "%.6g",
                                _ => "%s",
                            };
                            self.line(&format!("{{ {vec_ty} {v} = {c}; printf(\"[\");"));
                            self.line(&format!("for (int64_t {i} = 0; {i} < {v}.len; {i}++) {{ if ({i}) printf(\", \"); printf(\"{fmt_str}\", {fmt_elem}); }}"));
                            self.line("printf(\"]\"); }");
                        }
                        _ => panic!("vulcan: cannot print {t:?}"),
                    }
                }
                if callee == "print" {
                    self.line("printf(\"\\n\");");
                }
                ("(void)0".into(), Ty::Void)
            }
            "clock" => ("vclock()".into(), Ty::F64),
            "rand" => ("vrand()".into(), Ty::I64),
            "input" => ("input_line()".into(), Ty::Str),
            "sleep_ms" => {
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::I64);
                (format!("(vsleep({c}), (void)0)"), Ty::Void)
            }
            "exit" => {
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::I64);
                (format!("(exit({c}), (void)0)"), Ty::Void)
            }
            "key_ready" => ("key_ready()".into(), Ty::I64),
            "read_key" => ("read_key()".into(), Ty::I64),
            "clear_screen" => ("(clear_screen(), (void)0)".into(), Ty::Void),
            "term_raw" => ("(term_raw(), (void)0)".into(), Ty::Void),
            "ms_now" => ("vms_now()".into(), Ty::I64),
            "rand_int" => {
                if args.len() != 2 { panic!("vulcan: rand_int(lo, hi) takes 2 args"); }
                let (lo, lt) = self.gen_expr(&args[0]); let lo = self.cast(&lo, &lt, &Ty::I64);
                let (hi, ht) = self.gen_expr(&args[1]); let hi = self.cast(&hi, &ht, &Ty::I64);
                (format!("vrand_int({lo}, {hi})"), Ty::I64)
            }
            "print_at" => {
                if args.len() != 3 { panic!("vulcan: print_at(x, y, s) takes 3 args"); }
                let (x, xt) = self.gen_expr(&args[0]); let x = self.cast(&x, &xt, &Ty::I64);
                let (y, yt) = self.gen_expr(&args[1]); let y = self.cast(&y, &yt, &Ty::I64);
                let (s, st) = self.gen_expr(&args[2]);
                if st != Ty::Str { panic!("vulcan: print_at needs a string"); }
                (format!("(vprint_at({x}, {y}, {s}), (void)0)"), Ty::Void)
            }
            "set_color" => {
                if args.len() != 2 { panic!("vulcan: set_color(fg, bg) takes 2 args (use -1 to skip one)"); }
                let (fg, ft) = self.gen_expr(&args[0]); let fg = self.cast(&fg, &ft, &Ty::I64);
                let (bg, bt) = self.gen_expr(&args[1]); let bg = self.cast(&bg, &bt, &Ty::I64);
                (format!("(vset_color({fg}, {bg}), (void)0)"), Ty::Void)
            }
            "screen_width" => ("vscreen_w()".into(), Ty::I64),
            "screen_height" => ("vscreen_h()".into(), Ty::I64),
            "cursor_visible" => {
                let (c, t) = self.gen_expr(&args[0]); let c = self.cast(&c, &t, &Ty::I64);
                (format!("(vcursor_visible({c}), (void)0)"), Ty::Void)
            }
            "term_normal" => ("(term_normal(), (void)0)".into(), Ty::Void),
            "sqrt" | "floor" | "ceil" | "sin" | "cos" | "pow" => {
                let (c, t) = self.gen_expr(&args[0]);
                let c = self.cast(&c, &t, &Ty::F64);
                if callee == "pow" {
                    let (e, et) = self.gen_expr(&args[1]);
                    let e = self.cast(&e, &et, &Ty::F64);
                    (format!("pow({c}, {e})"), Ty::F64)
                } else {
                    (format!("{callee}({c})"), Ty::F64)
                }
            }
            "abs" => {
                let (c, t) = self.gen_expr(&args[0]);
                if t == Ty::I64 {
                    (format!("((({c}) < 0) ? -({c}) : ({c}))"), Ty::I64)
                } else if t == Ty::F64 {
                    (format!("fabs({c})"), Ty::F64)
                } else {
                    panic!("vulcan: abs needs an i64 or f64 argument");
                }
            }
            "min" | "max" => {
                if args.len() != 2 { panic!("vulcan: {callee} takes 2 args"); }
                let (a, at) = self.gen_expr(&args[0]);
                let (b, bt) = self.gen_expr(&args[1]);
                if at == Ty::F64 || bt == Ty::F64 {
                    let a = self.cast(&a, &at, &Ty::F64);
                    let b = self.cast(&b, &bt, &Ty::F64);
                    let f = if callee == "min" { "vmin_f64" } else { "vmax_f64" };
                    (format!("{f}({a}, {b})"), Ty::F64)
                } else if self.norm(&at) == Ty::I64 && self.norm(&bt) == Ty::I64 {
                    let f = if callee == "min" { "vmin_i64" } else { "vmax_i64" };
                    (format!("{f}({a}, {b})"), Ty::I64)
                } else {
                    panic!("vulcan: {callee} needs two numbers");
                }
            }
            "to_string" => {
                let (c, t) = self.gen_expr(&args[0]);
                let tmp = self.fresh("s");
                match t {
                    Ty::I64 => self.line(&format!("char {tmp}[32]; snprintf({tmp}, 32, \"%lld\", (long long){c});")),
                    Ty::F64 => self.line(&format!("char {tmp}[40]; snprintf({tmp}, 40, \"%.6g\", {c});")),
                    _ => panic!("vulcan: to_string needs i64 or f64"),
                }
                (tmp, Ty::Str)
            }
            _ => {
                let (ptys, ret) = self.fns.get(callee).unwrap_or_else(|| panic!("vulcan: call to unknown function `{callee}`")).clone();
                if args.len() != ptys.len() {
                    panic!("vulcan: {callee} expects {} args, got {}", ptys.len(), args.len());
                }
                let mut cs = Vec::new();
                for (a, pt) in args.iter().zip(&ptys) {
                    let (c, t) = self.gen_expr(a);
                    cs.push(self.cast(&c, &t, pt));
                }
                (format!("{}({})", safe_c_name(callee), cs.join(", ")), ret)
            }
        }
    }
}
