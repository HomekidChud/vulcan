// Python backend — transpiles Vulcan to Python 3 source.
// Structs become classes with real methods (impl blocks map to class methods);
// arrays become lists. Like the JS backend, struct assignment has reference
// semantics (the C backend copies).
use crate::parser::*;
use std::collections::HashMap;
use std::fmt::Write;

